import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { env } from './config/env';
import authRoutes from './routes/auth';
import productRoutes from './routes/products';
import categoryRoutes from './routes/categories';
import roleRoutes from './routes/roles';
import moduleRoutes from './routes/modules';
import employeeRoutes from './routes/employees';
import auditRoutes from './routes/auditLogs';
import permissionsRoutes from './routes/permissions';
import { errorHandler } from './middleware/errorHandler';

export const app=express();
app.disable('x-powered-by');
app.use(helmet());
const allowedOrigins=env.CORS_ORIGIN.split(',').map(x=>x.trim()).filter(Boolean);
app.use(cors({origin(origin,callback){if(!origin||allowedOrigins.includes(origin))return callback(null,true);return callback(new Error('Origin not allowed by CORS'));},credentials:true}));
app.use(express.json({limit:'1mb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({success:true,message:'API is healthy',data:{status:'ok',timestamp:new Date().toISOString()}}));
app.use('/api/auth',authRoutes);
app.use('/api/products',productRoutes);
app.use('/api/categories',categoryRoutes);
app.use('/api/roles',roleRoutes);
app.use('/api/permissions',permissionsRoutes);
app.use('/api/modules',moduleRoutes);
app.use('/api/employees',employeeRoutes);
app.use('/api/audit-logs',auditRoutes);
app.use((_req,res)=>res.status(404).json({success:false,message:'Route not found'}));
app.use(errorHandler);